SPELLING_INFO: dict[str, str] = {
    # 2011 оны тогтоолоор журамласан боловч практикт өөрөөр бичих нь түгээмэл
    "хэрэв": "хэрвээ (2011 оны тогтоол)",
    "цээж": "чээж (2011 оны тогтоол)",
    "хөвгүүн": "хөвүүн (2011 оны тогтоол)",
}

SPELLING_ORDERED = sorted(SPELLING.items(), key=lambda kv: -len(kv[0]))

BACK = set("аоуяёюы")
FRONT = set("эөү")
CODE_FENCE = re.compile(r"^\s*(```|~~~)")
INLINE_CODE = re.compile(r"`[^`]*`")
URL = re.compile(r"https?://\S+")
EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿⭐⭕←-⇿]")


def strip_noise(lines: list[str]) -> list[str]:
    """Код, YAML, URL-ийг хоосон болгоно (мөрийн дугаарыг хадгална)."""
    out, in_code, in_yaml = [], False, False
    for i, line in enumerate(lines):
        if i == 0 and line.strip() == "---":
            in_yaml = True
            out.append("")
            continue
        if in_yaml:
            if line.strip() == "---":
                in_yaml = False
            out.append("")
            continue
        if CODE_FENCE.match(line):
            in_code = not in_code
            out.append("")
            continue
        if in_code:
            out.append("")
            continue
        out.append(URL.sub(" ", INLINE_CODE.sub(" ", line)))
    return out


def sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.!?…])\s+", text) if s.strip()]


def analyze(raw: str) -> tuple[list[Hit], dict]:
    lines = strip_noise(raw.splitlines())
    hits: list[Hit] = []

    for n, line in enumerate(lines, 1):
        if not line.strip():
            continue

        for pat, rule, weight, note in PHRASES:
            for m in re.finditer(pat, line, re.IGNORECASE):
                hits.append(Hit(n, rule, weight, line[m.start():m.end()].strip(" .!?"), note))

        # §8 зураас (хязгаарын зураасыг алгасна: 10—20, XV—XX, 09:00—18:00)
        for m in re.finditer(r"\s--\s|[—–]", line):
            before, after = line[max(0, m.start() - 1):m.start()], line[m.end():m.end() + 1]
            if re.match(r"[0-9IVXLC]", before or " ") and re.match(r"[0-9IVXLC§]", after or " "):
                continue
            hits.append(Hit(n, "§8", "сул", line[max(0, m.start() - 15):m.end() + 15].strip(),
                            "зураас: 61-р зүйлийн дөрвөн тохиолдлын нэг үү?"))

        # §19 тод бичгийн шошготой жагсаалт
        if re.match(r"^\s*[-*]\s+\*\*[^*]+:\*\*", line) or re.match(r"^\s*[-*]\s+\*\*[^*]+\*\*:", line):
            hits.append(Hit(n, "§19", "дунд", line.strip()[:60], "тод шошготой жагсаалт"))

        # §20 гарчиг
        h = re.match(r"^\s*#{1,6}\s+(.*)$", line)
        if h:
            title = h.group(1).strip()
            words = [w for w in re.findall(r"[А-ЯЁӨҮа-яёөү]+", title)]
            caps = [w for w in words[1:] if w[0].isupper() and not w.isupper()]
            if len(caps) >= 2 and len(caps) >= (len(words) - 1) / 2:
                hits.append(Hit(n, "§20", "дунд", title, "гарчгийн үг бүр томоор: зөвхөн эхний үг, оноосон нэр"))
            if EMOJI.search(title):
                hits.append(Hit(n, "§20", "дунд", title, "гарчигт эможи, сум"))
            if title.endswith("."):
                hits.append(Hit(n, "§20", "сул", title, "гарчгийн эцэст цэг тавихгүй (51-р зүйл)"))
        elif EMOJI.search(line):
            hits.append(Hit(n, "§20", "сул", line.strip()[:60], "эможи чимэглэл"))

        # §21 «гэж»-ийн өмнөх таслал
        for m in re.finditer(r"[\"”»]\s*,\s*гэ(ж|в|сэн|жээ)\b", line):
            hits.append(Hit(n, "§21", "дунд", line[max(0, m.start() - 20):m.end()].strip(),
                            "шууд ярианы дараа «гэж»-ийн өмнө таслал тавихгүй"))

        # Зөв бичих: үгийн жагсаалт
        for m in re.finditer(r"[А-ЯЁӨҮа-яёөүъь]+", line):
            w = m.group(0)
            lw = w.lower()
            for bad, good in SPELLING_ORDERED:
                if lw == bad or (len(bad) >= 5 and lw.startswith(bad) and bad not in ("хэддэх",)):
                    hits.append(Hit(n, "зөв бичих", "хүчтэй", w, f"→ {good}{lw[len(bad):]}"))
                    break
            else:
                if lw in SPELLING_INFO:
                    hits.append(Hit(n, "зөв бичих", "сул", w, f"→ {SPELLING_INFO[lw]}"))
            # ы эм үгэнд
            letters = set(lw)
            if "ы" in letters and letters & FRONT and not (letters & (BACK - {"ы"})):
                hits.append(Hit(n, "зөв бичих", "дунд", w, "эм үгэнд «ы» бичихгүй, «ий» (§10)"))

        # бэ / вэ
        for m in re.finditer(r"([А-Яа-яЁёӨөҮүь]+)\s+(бэ|вэ)\b", line):
            word, q = m.group(1).lower(), m.group(2)
            want = "бэ" if word[-1] in "влмн" else "вэ"
            if q != want:
                hits.append(Hit(n, "зөв бичих", "дунд", m.group(0), f"«{word}» үгийн дараа «{want}» (§50)"))
        # уу/үү -> юу/юү урт, хос эгшгийн дараа
        for m in re.finditer(r"([А-Яа-яЁёӨөҮү]+)\s+(уу|үү)\?", line):
            word = m.group(1).lower()
            if re.search(r"(аа|ээ|оо|өө|уу|үү|ай|ой|уй|эй|ий|ы)$", word):
                want = "юу" if m.group(2) == "уу" else "юү"
                hits.append(Hit(n, "зөв бичих", "дунд", m.group(0), f"урт, хос эгшгийн дараа «{want}» (§50)"))

    # Бичвэрийн түвшний шалгалт
    text = "\n".join(lines)
    sents = sentences(re.sub(r"\s+", " ", text))
    starts = [re.match(r"[«\"“(]*(\w+(\s+нь)?)", s) for s in sents]
    starts = [m.group(1).lower() if m else "" for m in starts]

    # §7 ижил эхлэл дараалан
    run = 1
    for i in range(1, len(starts)):
        if starts[i] and starts[i] == starts[i - 1]:
            run += 1
            if run == 3:
                hits.append(Hit(0, "§7", "дунд", sents[i][:60], f"гурван өгүүлбэр дараалан «{starts[i]}»-ээр эхэлсэн"))
        else:
            run = 1

    # §29 «Энэ нь» гинж
    ene = sum(1 for s in starts if s in ("энэ нь", "энэхүү", "энэ"))
    if sents and ene >= 3 and ene / len(sents) >= 0.15:
        hits.append(Hit(0, "§29", "дунд", f"{ene}/{len(sents)} өгүүлбэр", "«Энэ нь...» гинжин өгүүлбэр (англи This/It)"))
    huvid = len(re.findall(r"\w+\s+хувьд\b", text))
    if huvid >= 3:
        hits.append(Hit(0, "§29", "сул", f"{huvid} удаа", "«...-ын хувьд» олон давтагдсан (as for)"))

    # §11 үйлдэгдэх хэвийн нягтрал
    words = re.findall(r"[А-ЯЁӨҮа-яёөү]+", text)
    passive = [w for w in words if re.search(r"(гд|гдэ|гда|гдо|гдө)(сан|сэн|сон|сөн|ж|аж|эж|ож|өж|даг|дэг|дог|дөг|ана|энэ|оно|өнө|ав|эв|ов|өв|ах|эх|ох|өх|сон|на|нэ|но|нө)\w*$", w.lower())]
    if words and len(passive) >= 4 and len(passive) / len(words) > 0.02:
        hits.append(Hit(0, "§11", "сул", ", ".join(passive[:6]), f"үйлдэгдэх хэв {len(passive)} удаа ({len(passive)/len(words):.1%})"))

    # §8 нийт зураас
    dashes = sum(1 for h in hits if h.rule == "§8")

    # §21 хашилтын холимог
    kinds = {k: len(re.findall(p, text)) for k, p in {"\"": r"\"", "“”": r"[“”]", "«»": r"[«»]"}.items()}
    used = [k for k, v in kinds.items() if v]
    if len(used) >= 2:
        hits.append(Hit(0, "§21", "сул", ", ".join(f"{k}:{kinds[k]}" for k in used), "хашилтын төрөл хольсон"))

    # §19 тод бичгийн нягт
    bold = len(re.findall(r"\*\*[^*\n]+\*\*", text))

    # §12 нийт
    w12 = sum(1 for h in hits if h.rule == "§12")

    latin = len(re.findall(r"\b[A-Za-z]{3,}\b", text))
    stats = {
        "үг": len(words),
        "өгүүлбэр": len(sents),
        "зураас": dashes,
        "тод бичиг": bold,
        "§12 үг": w12,
        "латин үг": latin,
    }
    hits.sort(key=lambda h: (h.line, h.rule))
    return hits, stats


def main() -> None:
    if hasattr(signal, "SIGPIPE"):
        signal.signal(signal.SIGPIPE, signal.SIG_DFL)
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    as_json = "--json" in sys.argv
    if not args:
        raise SystemExit(__doc__)
    path = args[0]
    raw = sys.stdin.read() if path == "-" else open(path, encoding="utf-8").read()
    hits, stats = analyze(raw)

    if as_json:
        print(json.dumps({"stats": stats, "hits": [asdict(h) for h in hits]}, ensure_ascii=False, indent=2))
        return

    order = {"хүчтэй": 0, "дунд": 1, "сул": 2}
    print("Нийт:", ", ".join(f"{k} {v}" for k, v in stats.items()))
    by_rule = Counter(h.rule for h in hits)
    print("Дүрмээр:", ", ".join(f"{k} {v}" for k, v in sorted(by_rule.items())) or "илрээгүй")
    print()
    for h in sorted(hits, key=lambda h: (order[h.weight], h.line)):
        where = f"{h.line}-р мөр" if h.line else "бүх бичвэр"
        print(f"[{h.weight}] {h.rule} {where}: {h.text}  — {h.note}")
    print()
    print("Тэмдэглэл: «сул» дохиог тухайн хэсэгт өөр шинжтэй хамт байвал л засна. "
          "Эшлэл, оноосон нэр, хэллэгийн тухай ярьж буй хэсгийг засахгүй.")


if __name__ == "__main__":
    main()
